const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.resolve(__dirname, '..');

function generateDataBundle() {
  // Use the same CSV parser as the app to keep bundled and live data identical.
  const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
  const context = {};
  vm.createContext(context);
  vm.runInContext(source.slice(source.indexOf('  function parseCSVText'), source.indexOf('  async function tryFetchLiveFiles')), context);
  const vocx = {}, dojo = {};
  for (const file of fs.readdirSync(path.join(root, 'vocx')).filter(file => /^\d+\.csv$/i.test(file)).sort()) {
    vocx[path.basename(file, '.csv')] = context.parseCSVText(fs.readFileSync(path.join(root, 'vocx', file), 'utf8'));
  }
  for (const folder of fs.readdirSync(path.join(root, 'dojo')).sort()) {
    const match = /^unit(\d+)$/i.exec(folder);
    if (!match) continue;
    const parts = {};
    for (const file of fs.readdirSync(path.join(root, 'dojo', folder)).filter(file => /^part\d+\.json$/i.test(file)).sort()) {
      parts[path.basename(file, '.json')] = JSON.parse(fs.readFileSync(path.join(root, 'dojo', folder, file), 'utf8'));
    }
    dojo[match[1].padStart(2, '0')] = parts;
  }
  return '// Generated by node scripts/build-data.cjs. Edit vocx/ and dojo/ source files.\n'
    + 'window.VOCX_FALLBACK_DATA=' + JSON.stringify(vocx) + ';\n'
    + 'window.DOJO_FALLBACK_DATA=' + JSON.stringify(dojo) + ';\n';
}

if (require.main === module) {
  const target = path.join(root, 'data.js');
  const before = fs.statSync(target).size;
  fs.writeFileSync(target, generateDataBundle());
  console.log(`data.js: ${before} -> ${fs.statSync(target).size} bytes`);
}
module.exports = { generateDataBundle };
