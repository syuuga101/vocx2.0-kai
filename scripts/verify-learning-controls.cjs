const fs = require('fs'), vm = require('vm'), assert = require('assert');
const js = fs.readFileSync('./app.js', 'utf8');
let now = 0;
const timer = {textContent: ''};
const c = {performance: {now: () => now}, currentSession: {}, document: {getElementById: () => timer}, setInterval() {return 1}, clearInterval() {}};
vm.createContext(c);
vm.runInContext(js.slice(js.indexOf('  let studyClock'), js.indexOf('  function loadState')), c);
c.startQuestionClock();
now = 65000; c.recordStudyTime();
assert.equal(c.currentSession.questionTimeMs, 65000);
assert.equal(timer.textContent, '01:05');
now = 67000; c.stopStudyClock();
now = 100000; c.recordStudyTime();
assert.equal(c.currentSession.questionTimeMs, 67000, 'time after answering or pausing is excluded');
c.startQuestionClock();
now = 103000; c.recordStudyTime();
assert.equal(timer.textContent, '01:10', 'resuming preserves the current question time');
c.stopStudyClock();
c.currentSession.questionTimeMs = 0;
c.startQuestionClock();
assert.equal(timer.textContent, '00:00', 'next question starts at zero');
now = 105000; c.recordStudyTime();
assert.equal(timer.textContent, '00:02');

const elements = {};
const el = id => elements[id] ||= {style: {}, value: '', innerHTML: '', textContent: '', listeners: {}, addEventListener(type, fn) {this.listeners[type] = fn}, focus() {}};
const q = {kind: 'vocx-eng-type', rawItem: {word: 'arise', inflected: 'arose', sentence: 'Difficulties arose yesterday.', def: 'To arise is to happen.'}};
const r = {cancelChoicePress: null,currentSession: {questions: [q], currentIndex: 0}, appState: {settings: {initialHint: false}}, document: {getElementById: el}, startQuestionClock() {}, updateProgressBar() {}, closeCheckSheet() {}, resetSlideThumb() {}, syncSlideAvailability() {}, escapeHtml: s => s, setTimeout() {}, submitTypeAnswer() {}};
vm.createContext(r);
vm.runInContext(js.slice(js.indexOf('  function buildBlankedSentence'), js.indexOf('  function startVocxQuiz')), r);
vm.runInContext(js.slice(js.indexOf('  function renderCurrentQuestion'), js.indexOf('  function escapeHtml')), r);
r.renderCurrentQuestion();
el('second-letter-hint').listeners.click();
assert.equal(el('type-hint-sentence').textContent, 'Difficulties ar____ yesterday.');
assert(r.currentSession.secondLetterHint);
assert(el('second-letter-hint').disabled);
el('type-hint-sentence').textContent = '';
r.renderCurrentQuestion();
assert.equal(el('type-hint-sentence').textContent, 'Difficulties ar____ yesterday.', 'hint survives rerender on resume');
console.log('OK: per-question timer stops, resumes and resets; second-letter hint survives resume');
